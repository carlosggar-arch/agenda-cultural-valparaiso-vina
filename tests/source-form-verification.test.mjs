import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
const node = {dataset: {}, textContent: ""};
const context = {window: {}, document: {querySelector: () => node}};
vm.runInNewContext(fs.readFileSync(new URL("../app/community-verification.js", import.meta.url), "utf8"), context);
assert.equal(context.window.communityVerificationError("110200"), true);
assert.match(node.textContent, /configuración de seguridad/);
assert.equal(node.dataset.verificationError, "110200");
context.window.communityVerificationReady();
assert.equal(node.dataset.verificationError, undefined);
assert.equal(node.textContent, "");
context.window.communityVerificationExpired();
assert.equal(node.dataset.verificationError, "expired");
assert.match(node.textContent, /caducado/);
context.window.communityVerificationReady();
context.window.communityVerificationError("300001");
assert.match(node.textContent, /Tus datos se conservan/);
const html = fs.readFileSync(new URL("../app/proponer-fuente.html", import.meta.url), "utf8");
assert.ok(html.indexOf("community-verification.js") < html.indexOf("challenges.cloudflare.com"));
assert.match(html, /data-error-callback="communityVerificationError"/);
const source = fs.readFileSync(new URL("../app/proponer-fuente.js", import.meta.url), "utf8");
assert.ok(source.indexOf("if (!values.turnstile_token)") < source.indexOf("await fetch("));
assert.match(source, /values.turnstile_token = values\["cf-turnstile-response"\]/);
console.log("Source form verification regressions passed");
